// Regenerate tests/fixtures/policyengine-us-files.txt, the list of every file
// under policyengine_us/parameters and policyengine_us/variables in the
// PolicyEngine-US commit that src/data/policyengineUsSnapshot.json pins.
//
// The uprating viewer links each row of public/data/uprating_analysis.csv to
// its source at that commit, and src/utils/policyengineUsSource.test.js checks
// every link against this list without a network. To move the pin, set
// "commit" in the snapshot file, then run this and the tests:
//
//   bun scripts/snapshot-policyengine-us-files.mjs
//   bun run test:run
//
// The script also reads the commit's release (the version in pyproject.toml)
// and its date (UTC) from GitHub. It writes both into the snapshot file, which
// the viewer's intro names, and into the list's header, which the tests check
// against the snapshot file. It reads GitHub's API; set GITHUB_TOKEN to raise
// the rate limit.
import { readFileSync, writeFileSync } from "node:fs";

const SNAPSHOT = "src/data/policyengineUsSnapshot.json";
const OUTPUT = "tests/fixtures/policyengine-us-files.txt";
const ROOTS = ["policyengine_us/parameters", "policyengine_us/variables"];

const snapshot = JSON.parse(readFileSync(SNAPSHOT, "utf8"));
const { repository, commit } = snapshot;
if (!/^[0-9a-f]{40}$/.test(commit)) {
  throw new Error(`${SNAPSHOT} must pin a full 40-character commit SHA`);
}

const headers = { "User-Agent": "ai-inequality-source-snapshot" };
if (process.env.GITHUB_TOKEN) {
  headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
}

async function github(path, accept = "application/vnd.github+json") {
  const url = `https://api.github.com/repos/${repository}/${path}`;
  const response = await fetch(url, {
    headers: { ...headers, Accept: accept },
  });
  if (!response.ok) {
    throw new Error(`${url} returned HTTP ${response.status}`);
  }
  return accept === "application/vnd.github.raw"
    ? response.text()
    : response.json();
}

async function listTree(sha, recursive = false) {
  const body = await github(
    `git/trees/${sha}${recursive ? "?recursive=1" : ""}`,
  );
  if (body.truncated) {
    throw new Error(`GitHub truncated the listing of tree ${sha}`);
  }
  return body.tree;
}

// Walks from the commit's root tree to a directory and returns its tree SHA.
async function treeSha(rootTree, directory) {
  let sha = rootTree;
  for (const name of directory.split("/")) {
    const entry = (await listTree(sha)).find(
      (item) => item.type === "tree" && item.path === name,
    );
    if (!entry) {
      throw new Error(`${repository}@${commit} has no ${directory}`);
    }
    sha = entry.sha;
  }
  return sha;
}

const { committer, tree } = await github(`git/commits/${commit}`);
const date = new Date(committer.date).toISOString().slice(0, 10);

const pyproject = await github(
  `contents/pyproject.toml?ref=${commit}`,
  "application/vnd.github.raw",
);
const project = pyproject
  .split(/^\[/m)
  .find((table) => table.startsWith("project]"));
const version = project?.match(/^version\s*=\s*"([^"]+)"/m)?.[1];
if (!version) {
  throw new Error(`pyproject.toml at ${commit} declares no [project] version`);
}

const files = [];
for (const root of ROOTS) {
  const entries = await listTree(await treeSha(tree.sha, root), true);
  for (const entry of entries) {
    if (entry.type === "blob") files.push(`${root}/${entry.path}`);
  }
}
files.sort();

if (snapshot.version !== version || snapshot.date !== date) {
  writeFileSync(
    SNAPSHOT,
    `${JSON.stringify({ ...snapshot, version, date }, null, 2)}\n`,
  );
  console.log(
    `${SNAPSHOT}: version ${snapshot.version} -> ${version}, date ${snapshot.date} -> ${date}`,
  );
}

const header = [
  `# Every file under ${ROOTS.join(" and ")}`,
  `# in ${repository} ${version}. Generated by`,
  "# scripts/snapshot-policyengine-us-files.mjs from GitHub's API; do not edit.",
  `# commit ${commit}`,
  `# version ${version}`,
  `# date ${date}`,
];
writeFileSync(OUTPUT, `${[...header, ...files].join("\n")}\n`);
console.log(
  `${OUTPUT}: ${files.length} files at ${repository}@${commit} (${version}, ${date})`,
);
