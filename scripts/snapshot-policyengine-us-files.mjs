// Regenerate tests/fixtures/policyengine-us-files.txt, the list of every file
// under policyengine_us/parameters and policyengine_us/variables in the
// PolicyEngine-US commit that src/data/policyengineUsSnapshot.json pins.
//
// The uprating viewer links each row of public/data/uprating_analysis.csv to
// its source at that commit, and src/utils/policyengineUsSource.test.js checks
// every link against this list without a network. Run this after changing the
// pin, then run the tests:
//
//   bun scripts/snapshot-policyengine-us-files.mjs
//
// It reads GitHub's tree API; set GITHUB_TOKEN to raise the rate limit.
import { readFileSync, writeFileSync } from "node:fs";

const SNAPSHOT = "src/data/policyengineUsSnapshot.json";
const OUTPUT = "tests/fixtures/policyengine-us-files.txt";
const ROOTS = ["policyengine_us/parameters", "policyengine_us/variables"];

const { repository, version, commit } = JSON.parse(
  readFileSync(SNAPSHOT, "utf8"),
);
if (!/^[0-9a-f]{40}$/.test(commit)) {
  throw new Error(`${SNAPSHOT} must pin a full 40-character commit SHA`);
}

const headers = {
  Accept: "application/vnd.github+json",
  "User-Agent": "ai-inequality-source-snapshot",
};
if (process.env.GITHUB_TOKEN) {
  headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
}

async function listTree(sha, recursive = false) {
  const url = `https://api.github.com/repos/${repository}/git/trees/${sha}${
    recursive ? "?recursive=1" : ""
  }`;
  const response = await fetch(url, { headers });
  if (!response.ok) {
    throw new Error(`${url} returned HTTP ${response.status}`);
  }
  const body = await response.json();
  if (body.truncated) {
    throw new Error(`GitHub truncated the listing at ${url}`);
  }
  return body.tree;
}

// Walks from the commit's root tree to a directory and returns its tree SHA.
async function treeSha(directory) {
  let sha = commit;
  for (const name of directory.split("/")) {
    const entry = (await listTree(sha)).find(
      (item) => item.type === "tree" && item.path === name,
    );
    if (!entry) {
      throw new Error(`${repository}@${commit} has no ${directory}`);
    }
    sha = entry.sha;
  }
  return sha;
}

const files = [];
for (const root of ROOTS) {
  const entries = await listTree(await treeSha(root), true);
  for (const entry of entries) {
    if (entry.type === "blob") files.push(`${root}/${entry.path}`);
  }
}
files.sort();

const header = [
  `# Every file under ${ROOTS.join(" and ")}`,
  `# in ${repository} ${version}. Generated by`,
  "# scripts/snapshot-policyengine-us-files.mjs from GitHub's tree API; do not edit.",
  `# commit ${commit}`,
];
writeFileSync(OUTPUT, `${[...header, ...files].join("\n")}\n`);
console.log(`${OUTPUT}: ${files.length} files at ${repository}@${commit}`);
